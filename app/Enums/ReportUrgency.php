<?php

namespace App\Enums;

enum ReportUrgency: string
{
    case Low = 'rendah';
    case Medium = 'sedang';
    case High = 'tinggi';

    public function label(): string
    {
        return match ($this) {
            self::Low => 'Rendah',
            self::Medium => 'Sedang',
            self::High => 'Tinggi',
        };
    }

    /**
     * Warna badge (nama warna Flux UI).
     */
    public function color(): string
    {
        return match ($this) {
            self::Low => 'zinc',
            self::Medium => 'amber',
            self::High => 'red',
        };
    }

    /**
     * Bobot untuk pengurutan (makin besar makin mendesak).
     */
    public function weight(): int
    {
        return match ($this) {
            self::Low => 1,
            self::Medium => 2,
            self::High => 3,
        };
    }

    /**
     * Opsi untuk dropdown/filter (nilai => label).
     *
     * @return array<string, string>
     */
    public static function options(): array
    {
        $options = [];

        foreach (self::cases() as $case) {
            $options[$case->value] = $case->label();
        }

        return $options;
    }
}
